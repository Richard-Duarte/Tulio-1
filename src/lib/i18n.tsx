type MessageKey = keyof (typeof messages)["pt"];
type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  /** Translates a key; `{name}` placeholders are replaced with `vars[name]`. */
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
};
const I18nContext = createContext<I18nValue | undefined>(undefined);
const STORAGE_KEY = "jula-language";

function readStoredLocale(): Locale {
  if (typeof window === "undefined") return "pt";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return locales.some((item) => item === stored) ? (stored as Locale) : "pt";
}

function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const text: string = messages[locale][key] ?? messages.pt[key];
  return vars
    ? text.replace(/\{(\w+)\}/g, (m, name: string) => String(vars[name] ?? m))
    : text;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readStoredLocale);
  useEffect(() => {
    document.documentElement.lang = locale === "pt" ? "pt-BR" : locale;
  }, [locale]);
  const value = useMemo<I18nValue>(
    () => ({
      locale,
      setLocale: (next) => {
        if (next === locale) return;
        setLocaleState(next);
        window.localStorage.setItem(STORAGE_KEY, next);
      },
      t: (key, vars) => translate(locale, key, vars),
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}

